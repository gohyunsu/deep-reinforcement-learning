// Each row: lecture slide (optionally @homework); prompt; answer; explanation.
// Multiple choice rows: reference; prompt; choices separated by ~; zero-based answer; explanation.
const parse = (raw, type) => raw.trim().split('\n').map((line, index) => {
  const parts = line.split(';').map(part => part.trim());
  if (parts.length !== (type === 'mc' ? 5 : 4)) throw new Error(`Malformed ${type} row ${index + 1}: ${line}`);
  const [reference, prompt, rawAnswer, explanation] = type === 'mc'
    ? [parts[0], parts[1], parts[3], parts[4]] : parts;
  const [slide, homework] = reference.split('@');
  const answer = type === 'tf' ? rawAnswer === 'T' : type === 'mc' ? Number(rawAnswer) : rawAnswer;
  return {type, slide, homework: homework || null, prompt, answer,
    choices: type === 'mc' ? parts[2].split('~').map(s => s.trim()) : null, explanation};
});

